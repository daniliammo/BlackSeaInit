#include "процессы.h"

#include "динамический_список.h"

#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>
#include <sys/wait.h>

static динамический_список отслеживаемые_процессы;

typedef struct {
    pid_t pid;
    демон *найденный;
} поиск_по_pid;

static void найти_по_pid(void *данные, void *контекст)
{
    демон *процесс = данные;
    поиск_по_pid *поиск = контекст;

    if (процесс->pid == поиск->pid) {
        поиск->найденный = процесс;
    }
}

static демон *найти_демон(pid_t pid)
{
    поиск_по_pid поиск = {
        .pid = pid,
        .найденный = NULL,
    };

    список_обойти(&отслеживаемые_процессы, найти_по_pid, &поиск);

    return поиск.найденный;
}

static int демон_в_списке(демон *процесс)
{
    for (узел_списка *узел = отслеживаемые_процессы.голова; узел != NULL; узел = узел->следующий) {
        if (узел->данные == процесс) {
            return 1;
        }
    }
    return 0;
}

static void добавить_в_список(демон *процесс)
{
    if (демон_в_списке(процесс)) {
        return;
    }

    if (список_добавить(&отслеживаемые_процессы, процесс) != 0) {
        fprintf(stderr, "Инициализация: не удалось добавить процесс в список\n");
    }
}

static int извлечь_код_выхода(int статус)
{
    if (WIFEXITED(статус)) {
        return WEXITSTATUS(статус);
    }
    if (WIFSIGNALED(статус)) {
        return 128 + WTERMSIG(статус);
    }
    return -1;
}

void запустить_процесс(демон *процесс, const char *команда)
{
    добавить_в_список(процесс);
    процесс->код_выхода = -1;

    pid_t pid = fork();

    if (pid < 0) {
        perror("Инициализация: fork");
        return;
    }

    if (pid == 0) {
        execl("/bin/sh", "sh", "-c", команда, NULL);
        perror("Инициализация: execl");
        _exit(127);
    }

    процесс->pid = pid;
}

static void выполнить_после_успеха(const char *действие)
{
    if (действие == NULL || действие[0] == '\0') {
        return;
    }

    pid_t pid = fork();

    if (pid < 0) {
        perror("Инициализация: fork (после_успеха)");
        return;
    }

    if (pid == 0) {
        execl("/bin/sh", "sh", "-c", действие, NULL);
        perror("Инициализация: execl (после_успеха)");
        _exit(127);
    }
}

void обработать_завершение_процесса(pid_t pid, int статус)
{
    демон *процесс = найти_демон(pid);
    if (процесс == NULL) {
        return;
    }

    процесс->код_выхода = извлечь_код_выхода(статус);

    if (процесс->код_выхода == 0) {
        выполнить_после_успеха(процесс->после_успеха);
    }

    процесс->pid = 0;
}
