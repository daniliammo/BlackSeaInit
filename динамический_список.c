#include "динамический_список.h"

#include <stdlib.h>

void список_инициализировать(динамический_список *список)
{
    список->голова = NULL;
    список->размер = 0;
}

int список_добавить(динамический_список *список, void *данные)
{
    узел_списка *узел = malloc(sizeof(узел_списка));
    if (узел == NULL) {
        return -1;
    }

    узел->данные = данные;
    узел->следующий = список->голова;
    список->голова = узел;
    список->размер++;

    return 0;
}

void *список_удалить(динамический_список *список, void *данные)
{
    узел_списка **текущий = &список->голова;

    while (*текущий != NULL) {
        if ((*текущий)->данные == данные) {
            узел_списка *удаляемый = *текущий;
            void *результат = удаляемый->данные;

            *текущий = удаляемый->следующий;
            free(удаляемый);
            список->размер--;

            return результат;
        }

        текущий = &(*текущий)->следующий;
    }

    return NULL;
}

void список_обойти(
    динамический_список *список,
    void (*действие)(void *данные, void *контекст),
    void *контекст
)
{
    for (узел_списка *узел = список->голова; узел != NULL; узел = узел->следующий) {
        действие(узел->данные, контекст);
    }
}

void список_очистить(динамический_список *список)
{
    узел_списка *узел = список->голова;

    while (узел != NULL) {
        узел_списка *следующий = узел->следующий;
        free(узел);
        узел = следующий;
    }

    список->голова = NULL;
    список->размер = 0;
}
