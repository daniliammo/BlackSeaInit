/* ─────────────────────────────────────────────────────────────────────────────
   конда_init.h — доверенный C-шим init'а (как stdlib/конда_ио.h, §32 3-слойная
   модель: POSIX ← C-шим ← Konda). Header-only (static inline) → компилируется
   прямо в сгенерированный .c, отдельная линковка не нужна.

   Здесь ровно один «сырой» приём, который безопасная модель Konda не пропускает
   напрямую: exec с NUL-терминированным argv (варарги/массив char**). Инкапсу-
   лируем фиксированный запуск busybox sh — Konda-код форкается и вызывает это
   в потомке, не работая с сырым char** сам.
   ────────────────────────────────────────────────────────────────────────── */
#pragma once
#include <unistd.h>
#include <stdio.h>

/* Заменяет образ потомка на интерактивный busybox sh. При успехе НЕ возвращается
   (execl). При ошибке печатает причину и завершает потомок кодом 127. */
[[noreturn]] static inline void конда_exec_оболочку(void) {
    execl("/bin/busybox", "sh", (char *)NULL);
    perror("Инициализация: execl");
    _exit(127);
}
